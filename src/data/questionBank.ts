const TARGET_CYCLE: OptionKey[] = ['C', 'A', 'D', 'B', 'A', 'C', 'B', 'D', 'A', 'C'];

export function shuffleQuestionOptions(q: Question, forcedTarget?: OptionKey): Question {
  const correctText = q.options[q.correctAnswer];
  const keys: OptionKey[] = ['A', 'B', 'C', 'D'];
  const wrongTexts = keys
    .filter(k => k !== q.correctAnswer)
    .map(k => q.options[k]);

  const targetKey: OptionKey = forcedTarget || keys[Math.floor(Math.random() * keys.length)];

  // Shuffle wrong texts
  const shuffledWrong = [...wrongTexts].sort(() => 0.5 - Math.random());

  const newOptions: Record<OptionKey, string> = {
    A: '',
    B: '',
    C: '',
    D: ''
  };

  let wrongIdx = 0;
  keys.forEach(k => {
    if (k === targetKey) {
      newOptions[k] = correctText;
    } else {
      newOptions[k] = shuffledWrong[wrongIdx++];
    }
  });

  return {
    ...q,
    options: newOptions as { A: string; B: string; C: string; D: string },
    correctAnswer: targetKey,
  };
}

/**
 * Pre-balanced question bank with answers evenly distributed across A, B, C, D
 */
export const BALANCED_QUESTION_BANK: Question[] = RAW_QUESTION_BANK.map((q, idx) => {
  const target = TARGET_CYCLE[idx % TARGET_CYCLE.length];
  return shuffleQuestionOptions(q, target);
});
